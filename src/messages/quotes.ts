export type QuotePool = keyof typeof QUOTES;

export function quoteId(pool: QuotePool, index: number): string {
  return `${pool}:${index}`;
}

/** Pick a quote, avoiding recently used ones when possible. */
export function pickQuote(pool: QuotePool, recent: readonly string[], random: () => number = Math.random): { id: string; text: string } {
  const lines = QUOTES[pool];
  const fresh = lines.map((_, i) => i).filter((i) => !recent.includes(quoteId(pool, i)));
  const candidates = fresh.length > 0 ? fresh : lines.map((_, i) => i);
  const index = candidates[Math.min(candidates.length - 1, Math.floor(random() * candidates.length))]!;
  return { id: quoteId(pool, index), text: lines[index]! };
}
